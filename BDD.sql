CREATE TABLE imageProfil (
    id_image_profil INT AUTO_INCREMENT,
    chemin_image_profil VARCHAR(100),
    PRIMARY KEY (id_image_profil)
);

CREATE TABLE Compte (
    pseudo VARCHAR(50),
    mdp VARCHAR(20),
    nom VARCHAR(50),
    prenom VARCHAR(50),
    adresse_mail VARCHAR(100),
    date_naiss DATE,
    date_crea_compte DATE,
    date_der_co DATE,
    niveau VARCHAR(20),
    id_image_profil INT,
    PRIMARY KEY (pseudo),
    FOREIGN KEY (id_image_profil) REFERENCES imageProfil(id_image_profil)
);

CREATE TABLE Jeu (
    id_jeu INT AUTO_INCREMENT,
    nom_jeu VARCHAR(50),
    prix REAL,
    date_sortie DATE,
    synopsis TEXT,
    chemin_jaquette VARCHAR(100),
    PRIMARY KEY (id_jeu)
);

CREATE TABLE Article (
    id_article INT AUTO_INCREMENT,
    pseudo VARCHAR(50),
    id_jeu INT,
    titre_article VARCHAR(100),
    contenu TEXT,
    note_redac INT,
    date_crea_article DATE,
    date_der_modif DATE,
    PRIMARY KEY (id_article),
    FOREIGN KEY (pseudo) REFERENCES Compte(pseudo),
    FOREIGN KEY (id_jeu) REFERENCES Jeu(id_jeu)
);

CREATE TABLE Categorie (
    id_categorie INT,
    nom_categorie VARCHAR(50),
    PRIMARY KEY (id_categorie)
);

CREATE TABLE estCategorie (
    id_categorie INT,
    id_jeu INT,
    PRIMARY KEY (id_categorie,id_jeu),
    FOREIGN KEY (id_categorie) REFERENCES Categorie(id_categorie),
    FOREIGN KEY (id_jeu) REFERENCES Jeu(id_jeu)
);

CREATE TABLE Support (
    id_support INT,
    nom_support VARCHAR(50),
    PRIMARY KEY (id_support)
);

CREATE TABLE estSupport (
    id_support INT,
    id_jeu INT,
    PRIMARY KEY (id_support,id_jeu),
    FOREIGN KEY (id_support) REFERENCES Support(id_support),
    FOREIGN KEY (id_jeu) REFERENCES Jeu(id_jeu)
);

CREATE TABLE Image (
    id_image INT,
    id_article INT,
    chemin_im VARCHAR(100),
    PRIMARY KEY (id_image),
    FOREIGN KEY (id_article) REFERENCES Article(id_article)
);

CREATE TABLE Avis (
    id_avis INT AUTO_INCREMENT,
    pseudo VARCHAR(50),
    id_jeu INT,
    titre_avis VARCHAR(50),
    texte TEXT,
    note INT,
    date_crea_avis DATE,
    PRIMARY KEY (id_avis),
    FOREIGN KEY (pseudo) REFERENCES Compte(pseudo),
    FOREIGN KEY (id_jeu) REFERENCES Jeu(id_jeu)
);

